/**
 * Skill Debugger — source instrumentation for interactive breakpoint execution.
 *
 * How it works:
 *  1. instrumentSource(source) transforms the skill code by injecting
 *     `await __bp(lineNo, captureFn)` before every non-blank statement.
 *
 *  2. The runtime `__bp` function (provided by SkillDebugger) decides at
 *     each call site whether to actually pause:
 *       - pause if   breakpointsRef.current.has(lineNo)
 *       - or if      stepModeRef.current === true  (Step Over)
 *       - otherwise  return immediately (fast-path, no cost)
 *
 *  3. The capture arrow function `() => { try { return { params, res, … }; } catch(_) { return {}; } }`
 *     is generated by static analysis of all variable declarations on lines
 *     *above* the current one. try/catch silently skips variables not yet
 *     assigned (temporal dead zone / not reached yet).
 *
 *  4. The instrumented source is wrapped in an async IIFE at the call site
 *     so that top-level `await __bp(…)` calls are syntactically valid even
 *     outside the skill's inner `async function run(params)` body.
 *
 * Execution by the debugger panel:
 *   const instrumented = instrumentSource(skill.source)
 *   const wrapped = `return (async function __bs_debug__() {\n${instrumented}\n})()`
 *   const fn = new Function('params', '__bp', 'fetch', 'console', wrapped)
 *   const output = await fn(params, bpFn, skillFetch, captureConsole)
 */

// ─── Static analysis helpers ──────────────────────────────────────────────────

/**
 * Scan lines 0..beforeIdx (exclusive) for declared variable/parameter names.
 * Handles: const/let/var x = ..., function f(a, b), (a, b) => ...
 * Always includes 'params' (outer argument to new Function).
 */
function collectVarNames(lines, beforeIdx) {
  const vars = new Set(['params'])
  const declRe = /(?:const|let|var)\s+([\w$]+)\s*(?:=|,|;|\n|$)/g
  const fnParamRe = /function\s*[\w$]*\s*\(([^)]*)\)/g
  const arrowParamRe = /(?:^|\s)\(([^)]*)\)\s*=>/g

  for (let i = 0; i < beforeIdx && i < lines.length; i++) {
    const line = lines[i]
    let m

    declRe.lastIndex = 0
    while ((m = declRe.exec(line)) !== null) {
      if (m[1] && /^[\w$]+$/.test(m[1])) vars.add(m[1])
    }

    fnParamRe.lastIndex = 0
    while ((m = fnParamRe.exec(line)) !== null) {
      m[1].split(',').forEach((p) => {
        const name = p.trim().replace(/[=\s].*/, '').replace(/^\.\.\./, '')
        if (name && /^[\w$]+$/.test(name)) vars.add(name)
      })
    }

    arrowParamRe.lastIndex = 0
    while ((m = arrowParamRe.exec(line)) !== null) {
      m[1].split(',').forEach((p) => {
        const name = p.trim().replace(/[=\s].*/, '').replace(/^\.\.\./, '')
        if (name && /^[\w$]+$/.test(name)) vars.add(name)
      })
    }
  }

  return [...vars]
}

/**
 * Build the runtime capture arrow function.
 * Uses try/catch to silently handle variables not yet in scope.
 *
 * Example:
 *   () => { try { return { params, res, html }; } catch(_) { return {}; } }
 */
function buildCaptureFn(varNames) {
  if (!varNames.length) return '() => ({})'
  return `() => { try { return { ${varNames.join(', ')} }; } catch(_) { return {}; } }`
}

// ─── Public API ───────────────────────────────────────────────────────────────

/**
 * Instrument `source` by injecting `await __bp(lineNo, captureFn)` before
 * every non-blank line. The returned string is the instrumented body only —
 * the caller is responsible for wrapping it in an async IIFE.
 *
 * @param {string} source - Original skill source code
 * @returns {string} Instrumented source (inject into async wrapper before eval)
 */
// Regex to detect lines that are continuations of a prior expression and must
// not be separated from it by an injected statement.
const CONTINUATION_RE = /^[.?:&|,)]|^\?\./

export function instrumentSource(source) {
  const lines = source.split('\n')
  const result = []

  for (let i = 0; i < lines.length; i++) {
    const lineNo = i + 1
    const trimmed = lines[i].trim()

    if (trimmed.length > 0 && !CONTINUATION_RE.test(trimmed)) {
      const varNames = collectVarNames(lines, i)
      const captureFn = buildCaptureFn(varNames)
      // Preserve indentation of the original line
      const indent = lines[i].match(/^(\s*)/)[1]
      result.push(`${indent}await __bp(${lineNo}, ${captureFn});`)
    }

    result.push(lines[i])
  }

  return result.join('\n')
}

/**
 * Serialize a runtime value for display in the variables panel.
 * Handles circular references, native objects (Response, etc.), and Promises.
 *
 * @param {unknown} v
 * @returns {unknown} A JSON-safe representation
 */
export function serializeVar(v) {
  if (v === null || v === undefined) return v
  if (typeof v === 'string' || typeof v === 'number' || typeof v === 'boolean') return v
  if (v instanceof Promise) return '<Promise>'
  if (typeof Response !== 'undefined' && v instanceof Response) {
    return `<Response status=${v.status} ok=${v.ok}>`
  }
  try {
    return JSON.parse(JSON.stringify(v))
  } catch {
    try { return String(v) } catch { return '<unserializable>' }
  }
}

/**
 * Format a console argument for log display.
 *
 * @param {unknown} v
 * @returns {string}
 */
export function fmtConsoleArg(v) {
  if (v == null) return String(v)
  if (typeof v === 'object') {
    try { return JSON.stringify(v) } catch { return '[object]' }
  }
  return String(v)
}
